// Human-readable label for a stored option value (used by the review screen and
// the server brief). Falls back to the raw value for free-text fields.
export function labelFor(optionKey, value) {
  const opts = OPTIONS[optionKey];
  if (!opts) return value;
  const found = opts.find((o) => o.value === value);
  return found ? found.label : value;
}
